#include <glad/glad.h>
#include <stdio.h>
#include <stdint.h>

/*
 * OpenGL ES 3.1 / GLSL ES 3.10
 *
 * Scenario examples for:
 *     glDispatchCompute(num_groups_x,
 *                       num_groups_y,
 *                       num_groups_z)
 *
 * This file demonstrates the behavior described in the
 * glDispatchCompute documentation.
 *
 * IMPORTANT:
 * A valid OpenGL ES 3.1 context must be current before
 * running these scenarios.
 *
 * Scenarios 1-9 assume that a valid GLSL ES 3.10 compute
 * shader program is currently active.
 */


/* ============================================================
 * GL ERROR NAME
 * ============================================================ */

static const char *gl_error_name(GLenum error)
{
    switch (error)
    {
        case GL_NO_ERROR:
            return "GL_NO_ERROR";

        case GL_INVALID_ENUM:
            return "GL_INVALID_ENUM";

        case GL_INVALID_VALUE:
            return "GL_INVALID_VALUE";

        case GL_INVALID_OPERATION:
            return "GL_INVALID_OPERATION";

        case GL_OUT_OF_MEMORY:
            return "GL_OUT_OF_MEMORY";

        default:
            return "UNKNOWN_GL_ERROR";
    }
}


/* ============================================================
 * CLEAR PREVIOUS GL ERRORS
 * ============================================================ */

static void clear_gl_errors(void)
{
    while (glGetError() != GL_NO_ERROR)
    {
        /* Clear previous errors. */
    }
}


/* ============================================================
 * DISPATCH HELPER
 * ============================================================ */

static void run_dispatch_scenario(
        const char *name,
        GLuint num_groups_x,
        GLuint num_groups_y,
        GLuint num_groups_z)
{
    GLenum error;

    /*
     * Remove errors generated by previous OpenGL ES calls.
     */
    clear_gl_errors();

    /*
     * Execute glDispatchCompute().
     */
    glDispatchCompute(
        num_groups_x,
        num_groups_y,
        num_groups_z
    );

    /*
     * Check the result of the dispatch call.
     */
    error = glGetError();

    printf(
        "%s\n",
        name
    );

    printf(
        "  Dispatch groups : (%u, %u, %u)\n",
        num_groups_x,
        num_groups_y,
        num_groups_z
    );

    printf(
        "  GL error        : %s\n",
        gl_error_name(error)
    );

    printf("\n");
}


/* ============================================================
 * SCENARIO 1
 *
 * Normal 1D dispatch
 *
 * Dispatches:
 *
 *     64 x 1 x 1 work groups
 *
 * This is a basic valid usage example.
 * ============================================================ */

void scenario_dispatch_normal_1d(void)
{
    run_dispatch_scenario(
        "Scenario 1 - Normal 1D dispatch",
        64,
        1,
        1
    );
}


