/* ============================================================
 * SCENARIO 7
 *
 * Query the implementation limit for X and demonstrate a
 * dispatch that exceeds the maximum.
 *
 * GL_MAX_COMPUTE_WORK_GROUP_COUNT is queried with index 0
 * for the X dimension.
 *
 * Expected error:
 *
 *     GL_INVALID_VALUE
 * ============================================================ */

void scenario_dispatch_exceed_max_x(void)
{
    GLint max_x = 0;

    glGetIntegeri_v(
        GL_MAX_COMPUTE_WORK_GROUP_COUNT,
        0,
        &max_x
    );

    printf(
        "Scenario 7 - Maximum X work-group count: %d\n",
        max_x
    );

    if (max_x < 0)
    {
        printf(
            "Unable to obtain a valid X work-group limit.\n\n"
        );
        return;
    }

    clear_gl_errors();

    glDispatchCompute(
        (GLuint)max_x + 1u,
        1,
        1
    );

    GLenum error = glGetError();

    printf(
        "  Dispatch groups : (%u, 1, 1)\n",
        (GLuint)max_x + 1u
    );

    printf(
        "  Expected error   : GL_INVALID_VALUE\n"
    );

    printf(
        "  Actual error     : %s\n\n",
        gl_error_name(error)
    );
}


